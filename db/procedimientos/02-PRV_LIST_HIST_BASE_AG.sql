CREATE OR ALTER PROCEDURE PRV_LIST_HIST_BASE_AG (
  P_COD_RECLAMO INTEGER
)
RETURNS (
  ORDEN                 INTEGER,
  COD_MENSAJE_CLIENTE   INTEGER,
  FECHA_HORA            TIMESTAMP,
  TIPO_HITO             VARCHAR(30),
  TEXTO_HITO            BLOB SUB_TYPE 1,
  RESULTADO             VARCHAR(100),
  COD_USUARIO           INTEGER,
  USUARIO               VARCHAR(50),
  COD_USUARIO_DESTINO   INTEGER,
  USUARIO_DESTINO       VARCHAR(50),
  MENSAJE               BLOB SUB_TYPE 1,
  ES_MENSAJE_CLIENTE    SMALLINT,
  VISIBLE_CLIENTE       SMALLINT,
  ADJUNTOS              INTEGER,
  COD_MENSAJE_RESPUESTA INTEGER
)
AS
DECLARE VARIABLE V_MENSAJE_EDITADO BLOB SUB_TYPE 1;
DECLARE VARIABLE V_ELIMINADO SMALLINT;
BEGIN
/*
  Nombre: PRV_LIST_HIST_BASE_AG
  Descripción: Movimientos no eliminados de un ticket en el orden de la v1, con nombres canónicos.
  Última modificación: 2026-10-16

  Precondiciones:
  - P_COD_RECLAMO no es NULL (lo valida el público).

  Postcondiciones:
  - Envuelve PROC_GET_HITOS_TICKET_PORTAL(P_COD_RECLAMO, 0): TIPO_HITO se calcula sobre la secuencia
    completa y el filtro de visibilidad lo aplica el público.
  - ORDEN es correlativo (1..n) en el orden de la v1 (FECHA_ORDEN, FECHA_HORA, COD_MENSAJE_CLIENTE),
    contando solo los no eliminados.
  - MENSAJE = MENSAJE_EDITADO si no está vacío; si no, MENSAJE original.
  - Nombres = COALESCE(USUARIOS.NOMBRE, USUARIOS.ALIAS), nunca el ALIAS que devuelve la v1.
*/
  ORDEN = 0;
  FOR
    SELECT H.COD_MENSAJE_CLIENTE, H.FECHA_HORA, H.TIPO_HITO, H.TEXTO_HITO, H.RESULTADO_RECLAMO,
           H.COD_USUARIO, COALESCE(U.NOMBRE, U.ALIAS),
           H.COD_USUARIO_DESTINO, COALESCE(UD.NOMBRE, UD.ALIAS),
           H.MENSAJE, H.MENSAJE_EDITADO, H.ES_MENSAJE_CLIENTE, H.VISIBLE_CLIENTE, H.ADJUNTOS,
           H.COD_MENSAJE_RESPUESTA, H.ELIMINADO
    FROM PROC_GET_HITOS_TICKET_PORTAL(:P_COD_RECLAMO, 0) H
    LEFT JOIN USUARIOS U  ON U.COD_USUARIO  = H.COD_USUARIO
    LEFT JOIN USUARIOS UD ON UD.COD_USUARIO = H.COD_USUARIO_DESTINO
    INTO :COD_MENSAJE_CLIENTE, :FECHA_HORA, :TIPO_HITO, :TEXTO_HITO, :RESULTADO,
         :COD_USUARIO, :USUARIO, :COD_USUARIO_DESTINO, :USUARIO_DESTINO,
         :MENSAJE, :V_MENSAJE_EDITADO, :ES_MENSAJE_CLIENTE, :VISIBLE_CLIENTE, :ADJUNTOS,
         :COD_MENSAJE_RESPUESTA, :V_ELIMINADO
  DO
  BEGIN
    IF (COALESCE(:V_ELIMINADO, 0) = 0) THEN
    BEGIN
      ORDEN = ORDEN + 1;
      IF (COALESCE(:V_MENSAJE_EDITADO, '') <> '') THEN
        MENSAJE = :V_MENSAJE_EDITADO;
      SUSPEND;
    END
  END
END^

SET TERM ; ^
