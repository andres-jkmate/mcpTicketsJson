SET TERM ^ ;

CREATE OR ALTER PROCEDURE PRV_LIST_TAREAS_BASE_AG (
  P_COD_DESARROLLADOR      INTEGER,
  P_COD_DESARROLLADOR_RESP INTEGER,
  P_COD_RECLAMO            INTEGER,
  P_ESTADOS                VARCHAR(500),
  P_SOLO_PENDIENTES        SMALLINT,
  P_PRIORIDAD              INTEGER,
  P_CREADA_DESDE           DATE,
  P_CREADA_HASTA           DATE,
  P_INCLUIR_DESCANSOS      SMALLINT
)
RETURNS (
  COD_ASIGNACION_JK3      INTEGER,
  NOMBRE                  TYPE OF COLUMN ASIGNACION_JK3.NOMBRE,
  DESCRIPCION             BLOB SUB_TYPE 1,
  ESTADO_ASIGNACION       TYPE OF COLUMN ASIGNACION_JK3.ESTADO_ASIGNACION,
  PRIORIDAD               INTEGER,
  COD_TIPO_ASIGNACION_JK3 INTEGER,
  TIPO_ASIGNACION         TYPE OF COLUMN TIPO_ASIGNACION_JK3.NOMBRE,
  COD_RECLAMO             INTEGER,
  COD_DESARROLLADOR       INTEGER,
  DESARROLLADOR           VARCHAR(100),
  COD_DESARROLLADOR_RESP  INTEGER,
  DESARROLLADOR_RESP      VARCHAR(100),
  HORAS_ESTIMADAS         INTEGER,
  FECHA_COMPROMISO        DATE,
  FECHA_HORA_CREA         TIMESTAMP
)
AS
BEGIN
/*
  Nombre: PRV_LIST_TAREAS_BASE_AG
  Descripción: Asignaciones de desarrollo (ASIGNACION_JK3) con NRO_TICKET normalizado a entero y
               nombres canónicos de desarrollador y responsable.
  Última modificación: 2026-10-16

  Precondiciones:
  - Al menos uno de P_COD_DESARROLLADOR, P_COD_DESARROLLADOR_RESP o P_COD_RECLAMO tiene valor
    (lo valida el público).

  Postcondiciones:
  - Sin restricción por ADMIN_DESARROLLADORES (igual que GET_ASIGNACION_DESARROLLADORES).
  - Si P_ESTADOS tiene valor, se ignora P_SOLO_PENDIENTES. Pendiente = no FINALIZADA ni ARCHIVADO.
  - COD_RECLAMO = NULL cuando NRO_TICKET está vacío o no es numérico.
  - Nombre de desarrollador: usuario vinculado sin alias DEV-*, si no el DEV-*, si no DESARROLLADORES.NOMBRE.
*/
  FOR
    SELECT A.COD_ASIGNACION_JK3, A.NOMBRE, A.DESCRIPCION, A.ESTADO_ASIGNACION, A.PRIORIDAD,
           A.COD_TIPO_ASIGNACION_JK3, T.NOMBRE,
           IIF(TRIM(A.NRO_TICKET) SIMILAR TO '[0-9]{1,9}', CAST(TRIM(A.NRO_TICKET) AS INTEGER), NULL),
           A.COD_DESARROLLADOR,
           COALESCE((SELECT FIRST 1 COALESCE(U.NOMBRE, U.ALIAS)
                     FROM USUARIOS U
                     WHERE U.COD_DESARROLLADOR = A.COD_DESARROLLADOR
                     ORDER BY IIF(U.ALIAS STARTING WITH 'DEV-', 1, 0), U.COD_USUARIO), D.NOMBRE),
           A.COD_DESARROLLADOR_RESP,
           COALESCE((SELECT FIRST 1 COALESCE(U.NOMBRE, U.ALIAS)
                     FROM USUARIOS U
                     WHERE U.COD_DESARROLLADOR = A.COD_DESARROLLADOR_RESP
                     ORDER BY IIF(U.ALIAS STARTING WITH 'DEV-', 1, 0), U.COD_USUARIO), DR.NOMBRE),
           A.HORAS_ESTIMADAS, CAST(A.FECHA_COMPROMISO AS DATE), A.FECHA_HORA_CREA
    FROM ASIGNACION_JK3 A
    LEFT JOIN TIPO_ASIGNACION_JK3 T ON T.COD_TIPO_ASIGNACION_JK3 = A.COD_TIPO_ASIGNACION_JK3
    LEFT JOIN DESARROLLADORES D  ON D.COD_DESARROLLADOR  = A.COD_DESARROLLADOR
    LEFT JOIN DESARROLLADORES DR ON DR.COD_DESARROLLADOR = A.COD_DESARROLLADOR_RESP
    WHERE (:P_COD_DESARROLLADOR IS NULL OR A.COD_DESARROLLADOR = :P_COD_DESARROLLADOR)
      AND (:P_COD_DESARROLLADOR_RESP IS NULL OR A.COD_DESARROLLADOR_RESP = :P_COD_DESARROLLADOR_RESP)
      AND (:P_COD_RECLAMO IS NULL OR TRIM(A.NRO_TICKET) = CAST(:P_COD_RECLAMO AS VARCHAR(20)))
      AND (:P_ESTADOS IS NULL OR (',' || :P_ESTADOS || ',') CONTAINING (',' || A.ESTADO_ASIGNACION || ','))
      AND (:P_ESTADOS IS NOT NULL OR COALESCE(:P_SOLO_PENDIENTES, 1) = 0
           OR A.ESTADO_ASIGNACION NOT IN ('FINALIZADA', 'ARCHIVADO'))
      AND (:P_PRIORIDAD IS NULL OR A.PRIORIDAD = :P_PRIORIDAD)
      AND (:P_CREADA_DESDE IS NULL OR A.FECHA_HORA_CREA >= :P_CREADA_DESDE)
      AND (:P_CREADA_HASTA IS NULL OR A.FECHA_HORA_CREA < DATEADD(1 DAY TO :P_CREADA_HASTA))
      AND (COALESCE(:P_INCLUIR_DESCANSOS, 0) = 1 OR COALESCE(A.ES_DESCANSO, 0) = 0)
    INTO :COD_ASIGNACION_JK3, :NOMBRE, :DESCRIPCION, :ESTADO_ASIGNACION, :PRIORIDAD,
         :COD_TIPO_ASIGNACION_JK3, :TIPO_ASIGNACION, :COD_RECLAMO,
         :COD_DESARROLLADOR, :DESARROLLADOR, :COD_DESARROLLADOR_RESP, :DESARROLLADOR_RESP,
         :HORAS_ESTIMADAS, :FECHA_COMPROMISO, :FECHA_HORA_CREA
  DO
    SUSPEND;
END^

SET TERM ; ^
