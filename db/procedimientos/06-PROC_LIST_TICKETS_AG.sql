CREATE OR ALTER PROCEDURE PROC_LIST_TICKETS_AG (
  P_ESTADOS            VARCHAR(500),
  P_SOLO_ABIERTOS      SMALLINT,
  P_PRIORIDADES        VARCHAR(200),
  P_SISTEMA            VARCHAR(7),
  P_COD_USUARIO_ASIG   INTEGER,
  P_AGENDADO_A         INTEGER,
  P_COD_CLIENTE        INTEGER,
  P_CREADO_DESDE       DATE,
  P_CREADO_HASTA       DATE,
  P_TEXTO              VARCHAR(100),
  P_BUSCAR_EN_MENSAJES SMALLINT,
  P_ORDEN              VARCHAR(15),
  P_LIMITE             INTEGER,
  P_DESPLAZAMIENTO     INTEGER
)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255), TOTAL INTEGER,
  COD_RECLAMO INTEGER, TITULO VARCHAR(200), ESTADO VARCHAR(50), PRIORIDAD VARCHAR(15), TIPO_SISTEMA VARCHAR(7),
  COD_CLIENTE INTEGER, CLIENTE VARCHAR(100), COD_USUARIO_ASIG INTEGER, USUARIO_ASIG VARCHAR(50),
  FECHA_CREACION TIMESTAMP, FECHA_ULTIMO_CAMBIO TIMESTAMP,
  AGENDA_FECHA TIMESTAMP, AGENDA_COD_USUARIO INTEGER, AGENDA_USUARIO VARCHAR(50),
  ESTADO_PRESUPUESTO VARCHAR(10)
)
AS
BEGIN
/*
  Nombre: PROC_LIST_TICKETS_AG
  Descripción: Listado liviano de tickets con filtros combinables, texto libre y paginación con TOTAL.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_LIMITE IS NULL OR :P_LIMITE < 1 OR :P_LIMITE > 100 OR COALESCE(:P_DESPLAZAMIENTO, -1) < 0) THEN
  BEGIN MENSAJE_ERROR = 'Límite entre 1 y 100 y desplazamiento >= 0'; SUSPEND; EXIT; END
  IF (:P_CREADO_DESDE IS NOT NULL AND :P_CREADO_HASTA IS NOT NULL AND :P_CREADO_DESDE > :P_CREADO_HASTA) THEN
  BEGIN MENSAJE_ERROR = 'La fecha desde es posterior a la fecha hasta'; SUSPEND; EXIT; END
  IF (:P_TEXTO IS NOT NULL AND CHAR_LENGTH(TRIM(:P_TEXTO)) < 3) THEN
  BEGIN MENSAJE_ERROR = 'El texto de búsqueda debe tener al menos 3 caracteres'; SUSPEND; EXIT; END
  IF (COALESCE(:P_ORDEN, 'actualizacion') NOT IN ('actualizacion', 'creacion', 'agenda')) THEN
  BEGIN MENSAJE_ERROR = 'Orden inválido'; SUSPEND; EXIT; END

  FOR
    SELECT COUNT(*) OVER (), B.COD_RECLAMO, B.TITULO, B.ESTADO, B.PRIORIDAD, B.TIPO_SISTEMA,
           B.COD_CLIENTE, B.CLIENTE, B.COD_USUARIO_ASIG, B.USUARIO_ASIG, B.FECHA_CREACION, B.FECHA_ULTIMO_CAMBIO,
           B.AGENDA_FECHA, B.AGENDA_COD_USUARIO, B.AGENDA_USUARIO, B.ESTADO_PRESUPUESTO
    FROM PRV_LIST_TICKETS_BASE_AG(NULL, :P_COD_CLIENTE, :P_COD_USUARIO_ASIG, :P_AGENDADO_A, :P_ESTADOS,
                                  :P_SOLO_ABIERTOS, :P_PRIORIDADES, :P_SISTEMA, :P_CREADO_DESDE, :P_CREADO_HASTA) B
    WHERE :P_TEXTO IS NULL
       OR B.TITULO COLLATE ES_ES_CI_AI CONTAINING :P_TEXTO
       OR B.PEDIDO_NORMALIZADO COLLATE ES_ES_CI_AI CONTAINING :P_TEXTO
       OR (COALESCE(:P_BUSCAR_EN_MENSAJES, 0) = 1 AND EXISTS (
             SELECT 1
             FROM DET_RECLAMOS_CLIENTES D
             JOIN MENSAJES_CLIENTES M ON M.COD_MENSAJE_CLIENTE = D.COD_MENSAJE_CLIENTE
             WHERE D.COD_RECLAMO = B.COD_RECLAMO
               AND COALESCE(M.ELIMINADO, 0) = 0
               AND M.MENSAJE COLLATE ES_ES_CI_AI CONTAINING :P_TEXTO))
    ORDER BY
      CASE WHEN COALESCE(:P_ORDEN, 'actualizacion') = 'actualizacion' THEN B.FECHA_ULTIMO_CAMBIO END DESC,
      CASE WHEN :P_ORDEN = 'creacion' THEN B.FECHA_CREACION END DESC,
      CASE WHEN :P_ORDEN = 'agenda' THEN B.AGENDA_FECHA END ASC NULLS LAST,
      B.COD_RECLAMO DESC
    OFFSET :P_DESPLAZAMIENTO ROWS FETCH NEXT :P_LIMITE ROWS ONLY
    INTO :TOTAL, :COD_RECLAMO, :TITULO, :ESTADO, :PRIORIDAD, :TIPO_SISTEMA, :COD_CLIENTE, :CLIENTE,
         :COD_USUARIO_ASIG, :USUARIO_ASIG, :FECHA_CREACION, :FECHA_ULTIMO_CAMBIO,
         :AGENDA_FECHA, :AGENDA_COD_USUARIO, :AGENDA_USUARIO, :ESTADO_PRESUPUESTO
  DO
  BEGIN
    RESULTADO = 1; MENSAJE_ERROR = '';
    SUSPEND;
  END
END^

SET TERM ; ^
