CREATE OR ALTER PROCEDURE PROC_LIST_AGENDAS_TICKET_AG (P_COD_RECLAMO INTEGER)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255),
  COD_EVENTO INTEGER, FECHA_EVENTO TIMESTAMP, FECHA_HASTA TIMESTAMP, TODO_DIA SMALLINT, REALIZADO SMALLINT,
  COD_USUARIO_AGENDA INTEGER, USUARIO_AGENDA VARCHAR(50)
)
AS
BEGIN
/*
  Nombre: PROC_LIST_AGENDAS_TICKET_AG
  Descripción: Agendas de un ticket sin título ni descripción (repiten datos del ticket); nombre desde USUARIOS.
               Misma fuente que PROC_GET_AGENDAS_TICKET_ADMIN, sin la fila "no agendado".
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_RECLAMO IS NULL) THEN BEGIN MENSAJE_ERROR = 'Falta el número de ticket'; SUSPEND; EXIT; END
  FOR
    SELECT E.COD_EVENTO, E.FECHA_EVENTO, E.FECHA_HASTA, E.TODO_DIA, E.REALIZADO,
           AE.COD_USUARIO, COALESCE(U.NOMBRE, U.ALIAS)
    FROM EVENTOS E
    JOIN AGENDA_EVENTOS AE ON AE.COD_AGENDA_EVENTO = E.COD_AGENDA
    LEFT JOIN USUARIOS U ON U.COD_USUARIO = AE.COD_USUARIO
    WHERE E.COD_RECLAMO = :P_COD_RECLAMO
    ORDER BY E.FECHA_EVENTO, E.COD_EVENTO
    INTO :COD_EVENTO, :FECHA_EVENTO, :FECHA_HASTA, :TODO_DIA, :REALIZADO, :COD_USUARIO_AGENDA, :USUARIO_AGENDA
  DO BEGIN RESULTADO = 1; MENSAJE_ERROR = ''; SUSPEND; END
END^

SET TERM ; ^
