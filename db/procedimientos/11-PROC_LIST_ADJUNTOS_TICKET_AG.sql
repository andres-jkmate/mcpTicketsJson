CREATE OR ALTER PROCEDURE PROC_LIST_ADJUNTOS_TICKET_AG (P_COD_RECLAMO INTEGER)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255),
  COD_ARCHIVO INTEGER, RUTA VARCHAR(500), RUTA_REAL VARCHAR(500), OBSERVACION VARCHAR(500),
  COD_MENSAJE_CLIENTE INTEGER, FECHA DATE
)
AS
BEGIN
/*
  Nombre: PROC_LIST_ADJUNTOS_TICKET_AG
  Descripción: Metadatos de adjuntos del ticket (nunca el contenido). Envuelve PROC_GET_ARCHIVO_ADJ_SAC_X_RECL.
               El nombre a mostrar (OBSERVACION o último segmento de RUTA_REAL) lo arma el MCP.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_RECLAMO IS NULL) THEN BEGIN MENSAJE_ERROR = 'Falta el número de ticket'; SUSPEND; EXIT; END
  FOR
    SELECT A.COD_ARCHIVO, A.RUTA, A.RUTA_REAL, A.OBSERVACION, A.COD_MENSAJE_CLIENTE, CAST(A.FECHA AS DATE)
    FROM PROC_GET_ARCHIVO_ADJ_SAC_X_RECL(:P_COD_RECLAMO) A
    ORDER BY A.FECHA, A.COD_ARCHIVO
    INTO :COD_ARCHIVO, :RUTA, :RUTA_REAL, :OBSERVACION, :COD_MENSAJE_CLIENTE, :FECHA
  DO BEGIN RESULTADO = 1; MENSAJE_ERROR = ''; SUSPEND; END
END^

SET TERM ; ^
