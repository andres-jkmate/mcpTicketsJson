CREATE OR ALTER PROCEDURE PROC_LIST_PRESUP_TICKET_AG (P_COD_RECLAMO INTEGER)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255),
  NRO_COMPROBANTE VARCHAR(15), FECHA DATE, ESTADO VARCHAR(10), IMPORTE NUMERIC(18,3), FECHA_HORA_APROBO TIMESTAMP
)
AS
BEGIN
/*
  Nombre: PROC_LIST_PRESUP_TICKET_AG
  Descripción: Presupuestos no anulados de un ticket (lógica de PROC_GET_PRES_TICKET_PORTAL), importe numérico.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_RECLAMO IS NULL) THEN BEGIN MENSAJE_ERROR = 'Falta el número de ticket'; SUSPEND; EXIT; END
  FOR
    SELECT RC.NRO_COMPROBANTE, C.FECHA,
           DECODE(RC.APROBADO, 1, 'APROBADO', 0, 'RECHAZADO', 'PENDIENTE'),
           C.TOTAL, RC.FECHA_HORA_APROBO
    FROM RECLAMOS_COMPROBANTES RC
    JOIN COMPROBANTES C ON C.COD_TALONARIO = RC.COD_TALONARIO AND C.NRO_COMPROBANTE = RC.NRO_COMPROBANTE
    JOIN TIPOS_COMPROBANTES TC ON TC.COD_TIPO_COMPROBANTE = C.COD_TIPO_COMPROBANTE
    WHERE RC.COD_RECLAMO = :P_COD_RECLAMO
      AND TC.TIPO_COMPROBANTE = 'Presupuesto'
      AND COALESCE(C.ANULADO, 0) = 0
    ORDER BY C.FECHA, RC.NRO_COMPROBANTE
    INTO :NRO_COMPROBANTE, :FECHA, :ESTADO, :IMPORTE, :FECHA_HORA_APROBO
  DO BEGIN RESULTADO = 1; MENSAJE_ERROR = ''; SUSPEND; END
END^

SET TERM ; ^
