CREATE OR ALTER PROCEDURE PROC_INS_DET_FAC_PROV_AG (
  P_COD_COMPROBANTE_PROVEEDOR INTEGER,
  P_ORDEN                     INTEGER,
  P_COD_ARTICULO              VARCHAR(50),
  P_MONTO                     NUMERIC(18,3),
  P_COD_CENTRO_COSTO          INTEGER
)
RETURNS (
  RESULTADO     SMALLINT,
  MENSAJE_ERROR VARCHAR(500)
)
AS
DECLARE VARIABLE V_PROV  INTEGER;
DECLARE VARIABLE V_FECHA DATE;
DECLARE VARIABLE V_DESC  VARCHAR(100);
DECLARE VARIABLE V_NETO  NUMERIC(18,3);
DECLARE VARIABLE V_NG    NUMERIC(18,3);
DECLARE VARIABLE V_EX    NUMERIC(18,3);
DECLARE VARIABLE V_IVA   NUMERIC(18,3);
DECLARE VARIABLE V_IMP   NUMERIC(18,3);
DECLARE VARIABLE V_PU    NUMERIC(18,3);
DECLARE VARIABLE V_ERR   INTEGER;
BEGIN
/*
  Nombre: PROC_INS_DET_FAC_PROV_AG
  Descripción: Segundo paso de registrar_factura_proveedor (una vez por ítem): calcula los importes
               de la línea con JKMT_TOTAL_IMPORTE_ART_PROV a partir del monto con impuestos y la
               inserta con PROC_GRA_SEM_DET_CTE_PROV_JK3, igual que el formulario (CANTIDAD = 1,
               IMPORTE = PRECIO_UNITARIO). Las percepciones las agrega después
               PROC_INSERT_SEMI_DET_PROV_ALI como alícuotas.
  Última modificación: 2026-10-24
*/
  RESULTADO = 0;
  SELECT COD_PROVEEDOR, FECHA FROM SEMI_COMPROBANTES_PROVEEDORES
  WHERE COD_COMPROBANTE_PROVEEDOR = :P_COD_COMPROBANTE_PROVEEDOR
  INTO :V_PROV, :V_FECHA;
  IF (:V_PROV IS NULL) THEN
  BEGIN
    MENSAJE_ERROR = 'No existe la cabecera temporal ' || COALESCE(CAST(:P_COD_COMPROBANTE_PROVEEDOR AS VARCHAR(20)), '');
    SUSPEND; EXIT;
  END
  SELECT DESCRIPCION FROM ARTICULOS WHERE COD_ARTICULO = :P_COD_ARTICULO INTO :V_DESC;
  IF (:V_DESC IS NULL) THEN
  BEGIN
    MENSAJE_ERROR = 'No existe el artículo ' || COALESCE(:P_COD_ARTICULO, '');
    SUSPEND; EXIT;
  END
  IF (:P_MONTO IS NULL OR :P_MONTO <= 0) THEN
  BEGIN
    MENSAJE_ERROR = 'El monto de la línea ' || COALESCE(CAST(:P_ORDEN AS VARCHAR(20)), '') || ' debe ser mayor a 0';
    SUSPEND; EXIT;
  END

  SELECT NETO_TOTAL, NO_GRAVADO, EXENTO, IVA, IMPUESTO, PRECIO_UNITARIO
  FROM JKMT_TOTAL_IMPORTE_ART_PROV(:P_COD_ARTICULO, :P_MONTO, :V_PROV, :V_FECHA)
  INTO :V_NETO, :V_NG, :V_EX, :V_IVA, :V_IMP, :V_PU;

  SELECT COD_ERROR FROM PROC_GRA_SEM_DET_CTE_PROV_JK3(:P_COD_COMPROBANTE_PROVEEDOR, :P_ORDEN, :P_COD_ARTICULO, :V_DESC, 1,
    :V_PU, :V_IVA, :V_IMP, :V_NETO, :V_NG, :V_EX, NULL, NULL, NULL, :P_COD_CENTRO_COSTO, NULL)
  INTO :V_ERR;
  IF (:V_ERR IS NOT NULL) THEN
  BEGIN
    MENSAJE_ERROR = 'No se pudo grabar la línea ' || :P_ORDEN;
    SUSPEND; EXIT;
  END

  RESULTADO = 1; MENSAJE_ERROR = '';
  SUSPEND;
END^

SET TERM ; ^
