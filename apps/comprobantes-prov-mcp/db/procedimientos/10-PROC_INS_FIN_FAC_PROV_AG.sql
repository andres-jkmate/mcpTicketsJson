SET TERM ^ ;

CREATE OR ALTER PROCEDURE PROC_INS_FIN_FAC_PROV_AG (
  P_COD_COMPROBANTE_PROVEEDOR INTEGER,
  P_COD_USUARIO               INTEGER
)
RETURNS (
  RESULTADO                 SMALLINT,
  MENSAJE_ERROR             VARCHAR(500),
  COD_COMPROBANTE_PROVEEDOR INTEGER,
  NRO_COMPROBANTE           VARCHAR(15),
  CODIGO_COMP               NUMERIC(13,0),
  COD_PROVEEDOR             INTEGER,
  RAZON_SOCIAL              VARCHAR(100),
  FECHA                     DATE,
  TOTAL                     NUMERIC(18,3),
  CUOTA                     INTEGER,
  FECHA_VENCIMIENTO         DATE,
  MONTO_CUOTA               NUMERIC(18,3)
)
AS
DECLARE VARIABLE V_R        SMALLINT;
DECLARE VARIABLE V_E        VARCHAR(500);
DECLARE VARIABLE V_COND     INTEGER;
DECLARE VARIABLE V_RECEP    DATE;
DECLARE VARIABLE V_MONEDA   INTEGER;
DECLARE VARIABLE V_CRED     INTEGER;
DECLARE VARIABLE V_INT_MORA NUMERIC(18,3);
DECLARE VARIABLE V_T_INT    CHAR(3);
DECLARE VARIABLE V_TIPO_INT VARCHAR(9);
DECLARE VARIABLE V_T_PER    CHAR(3);
DECLARE VARIABLE V_PAGO     INTEGER;
DECLARE VARIABLE V_HONOR    NUMERIC(13,0);
DECLARE VARIABLE V_ERR      INTEGER;
BEGIN
/*
  Nombre: PROC_INS_FIN_FAC_PROV_AG
  Descripción: Último paso de registrar_factura_proveedor, como Grabar() del formulario: alícuotas y
               totales (PROC_INSERT_SEMI_DET_PROV_ALI), crédito y cuotas según la condición
               (PROC_INSERT_SEMI_CREDITO_PROV, LIST_FINANCIAR_CREDITO_PROV, PROC_INSERT_SEMI_CUOTAS_PROV),
               pase a las tablas reales (PROC_GUARDAR_SEMI_COMPPROVEEDOR), stock
               (PROC_INGRESAR_STOCK_CBTE_PROV) y limpieza de SEMI (PROC_BORRAR_SEMI_Y_DET_CTE_PROV).
               Devuelve una fila por cuota grabada, con los datos del comprobante en cada una.
               No confirma: corre dentro de la transacción de escritura del MCP.
  Última modificación: 2026-10-24

  Verificado contra CREAR_JK3_20261016 (2026-10-25):
  - Firmas de los SP de JK3 llamados; INTERES_MORA es NUMERIC(9,3), TIEMPO_* CHAR(3), TIPO VARCHAR(9).
  - ES_NETO de PROC_INSERT_SEMI_DET_PROV_ALI no se usa; ese SP devuelve RESULTADO = 1 al terminar.
  - PROC_GUARDAR_SEMI_COMPPROVEEDOR devuelve RESULTADO = 1 (solo -1 con retenciones) y no borra
    las SEMI (lo hace PROC_BORRAR_SEMI_Y_DET_CTE_PROV).
  - LIST_FINANCIAR_CREDITO_PROV reparte TOTAL / cuotas sin ajustar el redondeo de la última.
  Sin controlar (el formulario tampoco): RESULTADO de PROC_INSERT_SEMI_CUOTAS_PROV y
  PROC_BORRAR_SEMI_Y_DET_CTE_PROV, y COD_ERROR de PROC_INGRESAR_STOCK_CBTE_PROV.
*/
  RESULTADO = 0;
  COD_COMPROBANTE_PROVEEDOR = :P_COD_COMPROBANTE_PROVEEDOR;

  SELECT ERROR, RESULTADO FROM PROC_INSERT_SEMI_DET_PROV_ALI(:P_COD_COMPROBANTE_PROVEEDOR, 1) INTO :V_E, :V_R;
  IF (:V_R IS DISTINCT FROM 1) THEN
  BEGIN
    MENSAJE_ERROR = COALESCE(:V_E, 'No se pudieron calcular las alícuotas');
    SUSPEND; EXIT;
  END

  SELECT S.COD_CONDICION_COMPRA, S.FECHA_RECEPCION_FAC, S.COD_MONEDA, S.TOTAL, S.NRO_COMPROBANTE, S.COD_PROVEEDOR
  FROM SEMI_COMPROBANTES_PROVEEDORES S WHERE S.COD_COMPROBANTE_PROVEEDOR = :P_COD_COMPROBANTE_PROVEEDOR
  INTO :V_COND, :V_RECEP, :V_MONEDA, :TOTAL, :NRO_COMPROBANTE, :COD_PROVEEDOR;

  SELECT INTERES_MORA, TIEMPO_INTERES_MORA, TIPO_INTERES_MORA, TIEMPO_PERIODO_INTERES
  FROM PROC_GET_COND_COMPRA_X_COD(:V_COND) INTO :V_INT_MORA, :V_T_INT, :V_TIPO_INT, :V_T_PER;

  SELECT RESULTADO, COD_CREDITO_PROVEEDOR FROM PROC_INSERT_SEMI_CREDITO_PROV(:COD_PROVEEDOR, :P_COD_COMPROBANTE_PROVEEDOR,
    :P_COD_USUARIO, :V_MONEDA, 'Factura-' || TRIM(:NRO_COMPROBANTE), :V_INT_MORA, :V_T_INT, :V_TIPO_INT, :V_T_PER,
    :V_RECEP, 0, 0, 0, NULL, 0, NULL, :TOTAL)
  INTO :V_R, :V_CRED;
  IF (:V_R IS DISTINCT FROM 1) THEN
  BEGIN
    MENSAJE_ERROR = 'No se pudo crear el crédito';
    SUSPEND; EXIT;
  END

  FOR SELECT CUOTA, PAGO, FECHA_VENCIMIENTO, MONTO_CUOTA FROM LIST_FINANCIAR_CREDITO_PROV(:V_COND, :TOTAL, :V_RECEP)
      INTO :CUOTA, :V_PAGO, :FECHA_VENCIMIENTO, :MONTO_CUOTA
  DO
    SELECT RESULTADO FROM PROC_INSERT_SEMI_CUOTAS_PROV(:V_CRED, :CUOTA, :V_PAGO, NULL, NULL, :P_COD_COMPROBANTE_PROVEEDOR,
      :V_CRED, NULL, :FECHA_VENCIMIENTO, NULL, :MONTO_CUOTA, 0, 0, 0, 0, 0, '') INTO :V_R;

  SELECT RESULTADO, MENSAJE_ERROR, CODIGO_COMP, CODIGO_HONORARIOS
  FROM PROC_GUARDAR_SEMI_COMPPROVEEDOR(:P_COD_COMPROBANTE_PROVEEDOR) INTO :V_R, :V_E, :CODIGO_COMP, :V_HONOR;
  IF (:V_R IS DISTINCT FROM 1) THEN
  BEGIN
    MENSAJE_ERROR = COALESCE(:V_E, 'No se pudo grabar el comprobante');
    SUSPEND; EXIT;
  END
  CODIGO_COMP = COALESCE(:CODIGO_COMP, :V_HONOR);

  SELECT COD_ERROR FROM PROC_INGRESAR_STOCK_CBTE_PROV(:P_COD_COMPROBANTE_PROVEEDOR) INTO :V_ERR;  -- no-op si el tipo no actualiza stock
  SELECT RESULTADO FROM PROC_BORRAR_SEMI_Y_DET_CTE_PROV(:P_COD_COMPROBANTE_PROVEEDOR) INTO :V_R;

  SELECT C.FECHA, C.TOTAL, P.RAZON_SOCIAL
  FROM COMPROBANTES_PROVEEDORES C JOIN PROVEEDORES P ON P.COD_PROVEEDOR = C.COD_PROVEEDOR
  WHERE C.COD_COMPROBANTE_PROVEEDOR = :P_COD_COMPROBANTE_PROVEEDOR
  INTO :FECHA, :TOTAL, :RAZON_SOCIAL;

  -- Una fila por cuota real, con lo que quedó grabado.
  RESULTADO = 1; MENSAJE_ERROR = '';
  FOR SELECT Q.CUOTA, Q.FECHA_VENCIMIENTO, Q.MONTO_CUOTA FROM CUOTAS_PROVEEDORES Q
      WHERE Q.COD_CREDITO_PROVEEDOR = :V_CRED ORDER BY Q.CUOTA, Q.PAGO
      INTO :CUOTA, :FECHA_VENCIMIENTO, :MONTO_CUOTA
  DO SUSPEND;
END^

SET TERM ; ^
