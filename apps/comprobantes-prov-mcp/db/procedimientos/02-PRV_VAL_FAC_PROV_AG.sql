CREATE OR ALTER PROCEDURE PRV_VAL_FAC_PROV_AG (
  P_COD_PROVEEDOR        INTEGER,
  P_COD_TIPO_COMPROBANTE INTEGER,
  P_NRO_COMPROBANTE      VARCHAR(15),
  P_FECHA                DATE,
  P_FECHA_CONTABLE       DATE,
  P_FECHA_IVA            DATE,
  P_COD_CONDICION_COMPRA INTEGER
)
RETURNS (
  CODIGO  VARCHAR(40),
  MENSAJE VARCHAR(500)
)
AS
DECLARE VARIABLE V_EMPRESA   INTEGER;
DECLARE VARIABLE V_CERRADO   SMALLINT;
DECLARE VARIABLE V_OK        SMALLINT;
DECLARE VARIABLE V_MSJ       VARCHAR(500);
DECLARE VARIABLE V_MODALIDAD VARCHAR(17);
BEGIN
/*
  Nombre: PRV_VAL_FAC_PROV_AG
  Descripción: Bloqueos de negocio de un borrador de factura de proveedor. Lo usan
               PROC_LIST_VAL_FAC_PROV_AG (preparar) y PROC_INS_FAC_PROV_AG (registrar).
  Última modificación: 2026-10-24

  Precondiciones:
  - P_NRO_COMPROBANTE ya viene normalizado (L-PPPP-NNNNNNNN) por el MCP.
  - Cualquier parámetro puede ser NULL (borrador incompleto): se saltean los controles que lo necesitan.

  Postcondiciones:
  - Una fila por bloqueo; sin filas = válido. CODIGO es estable: BASE_NO_SOPORTADA,
    PROVEEDOR_INHABILITADO, COMPROBANTE_DUPLICADO, NUMERO_INVALIDO, FECHA_IVA_ANTERIOR,
    PERIODO_CERRADO o CONDICION_NO_CUENTA_CORRIENTE.
  - El duplicado lo decide PROC_CTRL_NRO_COMPPROV (compara el número exacto y valida la máscara):
    su mensaje "Ya se ha cargado..." es COMPROBANTE_DUPLICADO y cualquier otro, NUMERO_INVALIDO.
  - Período cerrado: PROC_VALIDAR_PER_CERRADO_EMPR sobre la empresa del tipo, para la fecha
    contable y para la de IVA.
*/
  IF (NOT EXISTS (SELECT 1 FROM TABLA_PRECOMPILADORES WHERE PRECOMPILADOR = 'PRJ_ARGENTINA')) THEN
  BEGIN
    CODIGO = 'BASE_NO_SOPORTADA'; MENSAJE = 'El prototipo solo registra facturas en bases de Argentina';
    SUSPEND;
  END

  IF (EXISTS (SELECT 1 FROM PROVEEDORES P WHERE P.COD_PROVEEDOR = :P_COD_PROVEEDOR
      AND P.FECHA_INHABILITACION IS NOT NULL AND P.FECHA_INHABILITACION <= CURRENT_DATE)) THEN
  BEGIN
    CODIGO = 'PROVEEDOR_INHABILITADO'; MENSAJE = 'El proveedor está inhabilitado';
    SUSPEND;
  END

  IF (:P_NRO_COMPROBANTE IS NOT NULL AND :P_COD_TIPO_COMPROBANTE IS NOT NULL AND :P_COD_PROVEEDOR IS NOT NULL) THEN
  BEGIN
    SELECT RESULTADO, MENSAJE FROM PROC_CTRL_NRO_COMPPROV(:P_COD_PROVEEDOR, :P_NRO_COMPROBANTE, :P_COD_TIPO_COMPROBANTE, NULL)
    INTO :V_OK, :V_MSJ;
    IF (:V_OK = 0) THEN
    BEGIN
      CODIGO = IIF(:V_MSJ STARTING WITH 'Ya se ha cargado', 'COMPROBANTE_DUPLICADO', 'NUMERO_INVALIDO');
      MENSAJE = :V_MSJ;
      SUSPEND;
    END
  END

  IF (:P_FECHA_IVA < :P_FECHA) THEN
  BEGIN
    CODIGO = 'FECHA_IVA_ANTERIOR'; MENSAJE = 'La fecha de IVA no puede ser anterior a la del comprobante';
    SUSPEND;
  END

  SELECT COD_EMPRESA FROM TIPOS_COMPROBANTES WHERE COD_TIPO_COMPROBANTE = :P_COD_TIPO_COMPROBANTE INTO :V_EMPRESA;
  IF (:V_EMPRESA IS NOT NULL) THEN
  BEGIN
    SELECT PERIODO_CERRADO FROM PROC_VALIDAR_PER_CERRADO_EMPR(:V_EMPRESA, 'MOD_COMPRA', :P_FECHA_CONTABLE) INTO :V_CERRADO;
    IF (:V_CERRADO = 1) THEN
    BEGIN
      CODIGO = 'PERIODO_CERRADO'; MENSAJE = 'La fecha contable cae en un período cerrado';
      SUSPEND;
    END
    SELECT PERIODO_CERRADO FROM PROC_VALIDAR_PER_CERRADO_EMPR(:V_EMPRESA, 'MOD_COMPRA', :P_FECHA_IVA) INTO :V_CERRADO;
    IF (:V_CERRADO = 1) THEN
    BEGIN
      CODIGO = 'PERIODO_CERRADO'; MENSAJE = 'La fecha de IVA cae en un período cerrado';
      SUSPEND;
    END
  END

  IF (:P_COD_CONDICION_COMPRA IS NOT NULL) THEN
  BEGIN
    SELECT MODALIDAD_PAGO FROM CONDICIONES_COMPRAS WHERE COD_CONDICION_COMPRA = :P_COD_CONDICION_COMPRA INTO :V_MODALIDAD;
    IF (COALESCE(:V_MODALIDAD, '') <> 'Cuenta Corriente') THEN
    BEGIN
      CODIGO = 'CONDICION_NO_CUENTA_CORRIENTE'; MENSAJE = 'El prototipo solo registra facturas a cuenta corriente';
      SUSPEND;
    END
  END
END^

SET TERM ; ^
