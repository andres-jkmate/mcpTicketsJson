CREATE OR ALTER PROCEDURE PRV_LIST_PERFIL_OPC_AG (
  P_COD_USUARIO INTEGER,
  P_COD_PERFIL  INTEGER
)
RETURNS (
  CAMPO       VARCHAR(20),
  CODIGO      INTEGER,
  DESCRIPCION VARCHAR(100),
  POR_DEFECTO SMALLINT,
  LETRA       CHAR(1),
  MODALIDAD   VARCHAR(17),
  COD_EMPRESA INTEGER
)
AS
DECLARE VARIABLE V_COD_USUARIO_CAJA INTEGER;
BEGIN
/*
  Nombre: PRV_LIST_PERFIL_OPC_AG
  Descripción: Perfiles de facturación de compras del usuario y, si P_COD_PERFIL es uno de ellos,
               las opciones de ese perfil (tipos, sucursales, centros de costo, condiciones y monedas).
  Última modificación: 2026-10-24

  Precondiciones:
  - P_COD_USUARIO es el usuario de la sesión del MCP (MCP_COD_USUARIO).

  Postcondiciones:
  - Una fila por opción. CAMPO: 'perfil', 'tipoComprobante', 'sucursal', 'centroCosto',
    'condicionCompra' o 'moneda' (los nombres de campo del contrato de la tool).
  - POR_DEFECTO = 1 si la opción está marcada por defecto en la lista del perfil (0 si es NULL).
  - Tipos: solo los "Factura" del perfil habilitados al usuario de caja en MOD_COMPRA (como
    PROC_GET_TIPO_COMP_USU_CAJA_PF); LETRA sale de CODIGO_AFIP ('001' A, '006' B, '011' C) y
    COD_EMPRESA es la empresa del tipo.
  - Condiciones: MODALIDAD = CONDICIONES_COMPRAS.MODALIDAD_PAGO.
  - Si P_COD_PERFIL es NULL o no está asignado al usuario, solo devuelve las filas 'perfil'.

  Pendiente de confirmar (design D7 y riesgos):
  - '006' = letra B: CREAR no tiene tipos B en el perfil para verificarlo.
  - El cruce de tipos usa COD_USUARIO_CAJA, como el formulario; para los usuarios 7 y 28 de CREAR
    da lo mismo que COD_USUARIO.
*/
  FOR SELECT P.COD_PERFIL_FACTURACION, P.DESCRIPCION, COALESCE(PU.POR_DEFECTO, 0)
      FROM PERFILES_FACTURACION_COMPRAS P
      JOIN PERFILES_FC_COMPRA_USUARIOS PU ON PU.COD_PERFIL_FACTURACION = P.COD_PERFIL_FACTURACION
      WHERE PU.COD_USUARIO = :P_COD_USUARIO
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO
  DO
  BEGIN
    CAMPO = 'perfil'; LETRA = NULL; MODALIDAD = NULL; COD_EMPRESA = NULL;
    SUSPEND;
  END

  IF (:P_COD_PERFIL IS NULL OR NOT EXISTS (SELECT 1 FROM PERFILES_FC_COMPRA_USUARIOS
      WHERE COD_PERFIL_FACTURACION = :P_COD_PERFIL AND COD_USUARIO = :P_COD_USUARIO)) THEN EXIT;

  SELECT COALESCE(U.COD_USUARIO_CAJA, U.COD_USUARIO) FROM USUARIOS U
  WHERE U.COD_USUARIO = :P_COD_USUARIO INTO :V_COD_USUARIO_CAJA;

  FOR SELECT TC.COD_TIPO_COMPROBANTE, TC.DESCRIPCION, COALESCE(PT.POR_DEFECTO, 0), T.COD_EMPRESA,
             CASE T.CODIGO_AFIP WHEN '001' THEN 'A' WHEN '006' THEN 'B' WHEN '011' THEN 'C' END
      FROM TIPOS_COMP_USUARIOS_ASIG(:V_COD_USUARIO_CAJA) TC
      JOIN TIPOS_COMPROBANTES_MODULOS M ON M.COD_TIPO_COMPROBANTE = TC.COD_TIPO_COMPROBANTE AND M.MODULO = 'MOD_COMPRA'
      JOIN PERFILES_FC_COMPRA_TIPOS_COMP PT ON PT.COD_TIPO_COMPROBANTE = TC.COD_TIPO_COMPROBANTE
      JOIN TIPOS_COMPROBANTES T ON T.COD_TIPO_COMPROBANTE = TC.COD_TIPO_COMPROBANTE
      WHERE PT.COD_PERFIL_FACTURACION = :P_COD_PERFIL AND TC.TIPO_COMPROBANTE = 'Factura'
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO, :COD_EMPRESA, :LETRA
  DO
  BEGIN
    CAMPO = 'tipoComprobante'; MODALIDAD = NULL;
    SUSPEND;
  END

  LETRA = NULL; COD_EMPRESA = NULL;
  FOR SELECT S.COD_SUCURSAL, S.NOMBRE, COALESCE(X.POR_DEFECTO, 0)
      FROM PERFILES_FC_COMPRA_SUCURSALES X
      JOIN SUCURSALES S ON S.COD_SUCURSAL = X.COD_SUCURSAL
      WHERE X.COD_PERFIL_FACTURACION = :P_COD_PERFIL
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO
  DO
  BEGIN
    CAMPO = 'sucursal';
    SUSPEND;
  END

  FOR SELECT C.COD_CENTRO_COSTO, C.DESCRIPCION, COALESCE(X.POR_DEFECTO, 0)
      FROM PERFILES_FC_COMPRA_CCOSTOS X
      JOIN CENTROS_COSTOS C ON C.COD_CENTRO_COSTO = X.COD_CENTRO_COSTO
      WHERE X.COD_PERFIL_FACTURACION = :P_COD_PERFIL
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO
  DO
  BEGIN
    CAMPO = 'centroCosto';
    SUSPEND;
  END

  FOR SELECT C.COD_CONDICION_COMPRA, C.DESCRIPCION, COALESCE(X.POR_DEFECTO, 0), C.MODALIDAD_PAGO
      FROM PERFILES_FC_COMPRA_COND_COMP X
      JOIN CONDICIONES_COMPRAS C ON C.COD_CONDICION_COMPRA = X.COD_CONDICION_COMPRA
      WHERE X.COD_PERFIL_FACTURACION = :P_COD_PERFIL
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO, :MODALIDAD
  DO
  BEGIN
    CAMPO = 'condicionCompra';
    SUSPEND;
  END

  MODALIDAD = NULL;
  -- PROC_GET_MONEDAS_PFC no filtra por perfil; acá sí.
  FOR SELECT M.COD_MONEDA, M.MONEDA, COALESCE(X.POR_DEFECTO, 0)
      FROM PERFILES_FC_COMPRA_MONEDAS X
      JOIN MONEDAS M ON M.COD_MONEDA = X.COD_MONEDA
      WHERE X.COD_PERFIL_FACTURACION = :P_COD_PERFIL
      INTO :CODIGO, :DESCRIPCION, :POR_DEFECTO
  DO
  BEGIN
    CAMPO = 'moneda';
    SUSPEND;
  END
END^

SET TERM ; ^
