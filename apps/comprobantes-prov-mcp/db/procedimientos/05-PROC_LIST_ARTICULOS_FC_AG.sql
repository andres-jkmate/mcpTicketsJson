CREATE OR ALTER PROCEDURE PROC_LIST_ARTICULOS_FC_AG (
  P_COD_PROVEEDOR INTEGER,
  P_TEXTO         VARCHAR(100)
)
RETURNS (
  RESULTADO            SMALLINT,
  MENSAJE_ERROR        VARCHAR(500),
  COD_ARTICULO         VARCHAR(50),
  DESCRIPCION          VARCHAR(100),
  CONDICION_IMPOSITIVA VARCHAR(50),
  ORIGEN               VARCHAR(20)
)
AS
DECLARE VARIABLE V_HAY SMALLINT = 0;
BEGIN
/*
  Nombre: PROC_LIST_ARTICULOS_FC_AG
  Descripción: Artículos que coinciden con P_TEXTO (CONTAINING sobre la descripción o código exacto),
               buscando por niveles y devolviendo solo el primero con resultados: plantilla del
               proveedor (PLANTILLAS_PROV_ARTICULOS), artículos de sus facturas anteriores y catálogo
               (ARTICULOS sin FECHA_BAJA). ORIGEN indica el nivel. Máximo 10.
               Con P_COD_PROVEEDOR NULL busca solo en el catálogo.
  Última modificación: 2026-10-24

  Pendiente de confirmar: si el catálogo debe filtrar además por ARTICULOS.BIEN_COMPRAS o por
  subgrupo de compras.
*/
  IF (COALESCE(TRIM(:P_TEXTO), '') = '') THEN
  BEGIN
    RESULTADO = 0; MENSAJE_ERROR = 'Indicá el artículo por texto o código';
    SUSPEND; EXIT;
  END

  RESULTADO = 1; MENSAJE_ERROR = '';
  FOR SELECT FIRST 10 A.COD_ARTICULO, A.DESCRIPCION, A.CONDICION_IMPUESTO_VENTA
      FROM PLANTILLAS_PROV_ARTICULOS PL
      JOIN ARTICULOS A ON A.COD_ARTICULO = PL.COD_ARTICULO
      WHERE PL.COD_PROVEEDOR = :P_COD_PROVEEDOR AND (A.DESCRIPCION CONTAINING :P_TEXTO OR A.COD_ARTICULO = :P_TEXTO)
      INTO :COD_ARTICULO, :DESCRIPCION, :CONDICION_IMPOSITIVA
  DO
  BEGIN
    ORIGEN = 'plantilla_proveedor'; V_HAY = 1;
    SUSPEND;
  END
  IF (:V_HAY = 1) THEN EXIT;

  FOR SELECT FIRST 10 DISTINCT A.COD_ARTICULO, A.DESCRIPCION, A.CONDICION_IMPUESTO_VENTA
      FROM DET_COMPROBANTES_PROVEEDORES D
      JOIN COMPROBANTES_PROVEEDORES C ON C.COD_COMPROBANTE_PROVEEDOR = D.COD_COMPROBANTE_PROVEEDOR
      JOIN ARTICULOS A ON A.COD_ARTICULO = D.COD_ARTICULO
      WHERE C.COD_PROVEEDOR = :P_COD_PROVEEDOR AND (A.DESCRIPCION CONTAINING :P_TEXTO OR A.COD_ARTICULO = :P_TEXTO)
      INTO :COD_ARTICULO, :DESCRIPCION, :CONDICION_IMPOSITIVA
  DO
  BEGIN
    ORIGEN = 'historial_proveedor'; V_HAY = 1;
    SUSPEND;
  END
  IF (:V_HAY = 1) THEN EXIT;

  FOR SELECT FIRST 10 A.COD_ARTICULO, A.DESCRIPCION, A.CONDICION_IMPUESTO_VENTA
      FROM ARTICULOS A
      WHERE A.FECHA_BAJA IS NULL AND (A.DESCRIPCION CONTAINING :P_TEXTO OR A.COD_ARTICULO = :P_TEXTO)
      INTO :COD_ARTICULO, :DESCRIPCION, :CONDICION_IMPOSITIVA
  DO
  BEGIN
    ORIGEN = 'catalogo';
    SUSPEND;
  END
END^

SET TERM ; ^
