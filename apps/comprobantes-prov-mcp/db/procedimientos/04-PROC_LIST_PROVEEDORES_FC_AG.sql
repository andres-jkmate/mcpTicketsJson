CREATE OR ALTER PROCEDURE PROC_LIST_PROVEEDORES_FC_AG (
  P_TEXTO         VARCHAR(100),
  P_COD_PROVEEDOR INTEGER
)
RETURNS (
  RESULTADO         SMALLINT,
  MENSAJE_ERROR     VARCHAR(500),
  COD_PROVEEDOR     INTEGER,
  RAZON_SOCIAL      VARCHAR(100),
  NOMBRE_COMERCIAL  VARCHAR(100),
  CUIT              VARCHAR(30),
  CANT_COMPROBANTES INTEGER,
  ULTIMA_FECHA      DATE
)
AS
BEGIN
/*
  Nombre: PROC_LIST_PROVEEDORES_FC_AG
  Descripción: Proveedores habilitados por código o por texto (CONTAINING sobre razón social y
               nombre comercial, o código/CUIT exacto), ordenados por cantidad de comprobantes.
               Máximo 10.
  Última modificación: 2026-10-24
*/
  IF (COALESCE(TRIM(:P_TEXTO), '') = '' AND :P_COD_PROVEEDOR IS NULL) THEN
  BEGIN
    RESULTADO = 0; MENSAJE_ERROR = 'Indicá el proveedor por texto o código';
    SUSPEND; EXIT;
  END

  RESULTADO = 1; MENSAJE_ERROR = '';
  FOR SELECT FIRST 10 P.COD_PROVEEDOR, P.RAZON_SOCIAL, P.NOMBRE_COMERCIAL, P.CUIT,
             (SELECT COUNT(*) FROM COMPROBANTES_PROVEEDORES C WHERE C.COD_PROVEEDOR = P.COD_PROVEEDOR),
             (SELECT MAX(C.FECHA) FROM COMPROBANTES_PROVEEDORES C WHERE C.COD_PROVEEDOR = P.COD_PROVEEDOR)
      FROM PROVEEDORES P
      WHERE (P.FECHA_INHABILITACION IS NULL OR P.FECHA_INHABILITACION > CURRENT_DATE)
        AND (P.COD_PROVEEDOR = :P_COD_PROVEEDOR
             OR (:P_COD_PROVEEDOR IS NULL AND (P.RAZON_SOCIAL CONTAINING :P_TEXTO OR P.NOMBRE_COMERCIAL CONTAINING :P_TEXTO
                 OR CAST(P.CODIGO AS VARCHAR(20)) = TRIM(:P_TEXTO) OR P.CUIT = TRIM(:P_TEXTO))))
      ORDER BY 5 DESC
      INTO :COD_PROVEEDOR, :RAZON_SOCIAL, :NOMBRE_COMERCIAL, :CUIT, :CANT_COMPROBANTES, :ULTIMA_FECHA
  DO SUSPEND;
END^

SET TERM ; ^
