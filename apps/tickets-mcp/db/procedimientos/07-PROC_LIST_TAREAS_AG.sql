CREATE OR ALTER PROCEDURE PROC_LIST_TAREAS_AG (
  P_COD_DESARROLLADOR      INTEGER,
  P_COD_DESARROLLADOR_RESP INTEGER,
  P_COD_RECLAMO            INTEGER,
  P_ESTADOS                VARCHAR(500),
  P_SOLO_PENDIENTES        SMALLINT,
  P_PRIORIDAD              INTEGER,
  P_CREADA_DESDE           DATE,
  P_CREADA_HASTA           DATE,
  P_INCLUIR_DESCANSOS      SMALLINT,
  P_LIMITE                 INTEGER,
  P_DESPLAZAMIENTO         INTEGER
)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255), TOTAL INTEGER,
  COD_ASIGNACION_JK3 INTEGER, NOMBRE VARCHAR(200), DESCRIPCION BLOB SUB_TYPE 1, ESTADO_ASIGNACION VARCHAR(35),
  PRIORIDAD INTEGER, COD_TIPO_ASIGNACION_JK3 INTEGER, TIPO_ASIGNACION VARCHAR(100), COD_RECLAMO INTEGER,
  COD_DESARROLLADOR INTEGER, DESARROLLADOR VARCHAR(100),
  COD_DESARROLLADOR_RESP INTEGER, DESARROLLADOR_RESP VARCHAR(100),
  HORAS_ESTIMADAS INTEGER, FECHA_COMPROMISO DATE, FECHA_HORA_CREA TIMESTAMP
)
AS
BEGIN
/*
  Nombre: PROC_LIST_TAREAS_AG
  Descripción: Tareas filtradas por desarrollador, responsable, ticket y estados, paginadas con TOTAL.
               DESCRIPCION siempre viaja; el MCP la descarta salvo incluirDescripcion = true.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_DESARROLLADOR IS NULL AND :P_COD_DESARROLLADOR_RESP IS NULL AND :P_COD_RECLAMO IS NULL) THEN
  BEGIN MENSAJE_ERROR = 'Indicar desarrollador, responsable o ticket'; SUSPEND; EXIT; END
  IF (:P_LIMITE IS NULL OR :P_LIMITE < 1 OR :P_LIMITE > 100 OR COALESCE(:P_DESPLAZAMIENTO, -1) < 0) THEN
  BEGIN MENSAJE_ERROR = 'Límite entre 1 y 100 y desplazamiento >= 0'; SUSPEND; EXIT; END
  IF (:P_CREADA_DESDE IS NOT NULL AND :P_CREADA_HASTA IS NOT NULL AND :P_CREADA_DESDE > :P_CREADA_HASTA) THEN
  BEGIN MENSAJE_ERROR = 'La fecha desde es posterior a la fecha hasta'; SUSPEND; EXIT; END

  FOR
    SELECT COUNT(*) OVER (), T.*
    FROM PRV_LIST_TAREAS_BASE_AG(:P_COD_DESARROLLADOR, :P_COD_DESARROLLADOR_RESP, :P_COD_RECLAMO, :P_ESTADOS,
                                 :P_SOLO_PENDIENTES, :P_PRIORIDAD, :P_CREADA_DESDE, :P_CREADA_HASTA,
                                 :P_INCLUIR_DESCANSOS) T
    ORDER BY T.PRIORIDAD, T.FECHA_HORA_CREA DESC, T.COD_ASIGNACION_JK3 DESC
    OFFSET :P_DESPLAZAMIENTO ROWS FETCH NEXT :P_LIMITE ROWS ONLY
    INTO :TOTAL, :COD_ASIGNACION_JK3, :NOMBRE, :DESCRIPCION, :ESTADO_ASIGNACION, :PRIORIDAD,
         :COD_TIPO_ASIGNACION_JK3, :TIPO_ASIGNACION, :COD_RECLAMO, :COD_DESARROLLADOR, :DESARROLLADOR,
         :COD_DESARROLLADOR_RESP, :DESARROLLADOR_RESP, :HORAS_ESTIMADAS, :FECHA_COMPROMISO, :FECHA_HORA_CREA
  DO
  BEGIN
    RESULTADO = 1; MENSAJE_ERROR = '';
    SUSPEND;
  END
END^

SET TERM ; ^
