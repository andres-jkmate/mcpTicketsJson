CREATE OR ALTER PROCEDURE PRV_LIST_TICKETS_BASE_AG (
  P_COD_RECLAMO      INTEGER,
  P_COD_CLIENTE      INTEGER,
  P_COD_USUARIO_ASIG INTEGER,
  P_AGENDADO_A       INTEGER,
  P_ESTADOS          VARCHAR(500),
  P_SOLO_ABIERTOS    SMALLINT,
  P_PRIORIDADES      VARCHAR(200),
  P_SISTEMA          VARCHAR(7),
  P_CREADO_DESDE     DATE,
  P_CREADO_HASTA     DATE
)
RETURNS (
  COD_RECLAMO         INTEGER,
  TITULO              VARCHAR(200),
  PEDIDO_NORMALIZADO  BLOB SUB_TYPE 1,
  ESTADO              TYPE OF COLUMN ESTADOS_RECLAMOS.ESTADO,
  RESULTADO           TYPE OF COLUMN RESULTADOS_RECLAMOS.DESCRIPCION,
  PRIORIDAD           TYPE OF COLUMN RECLAMOS.PRIORIDAD,
  TIPO_SISTEMA        TYPE OF COLUMN RECLAMOS.TIPO_SISTEMA,
  COD_PROCESO_SISTEMA INTEGER,
  PROCESO_SISTEMA     TYPE OF COLUMN PROCESOS_SISTEMAS.NOMBRE,
  COD_CLIENTE         INTEGER,
  CLIENTE             TYPE OF COLUMN CLIENTES.NOMBRE,
  CONTACTO            TYPE OF COLUMN RECLAMOS.CONTACTO,
  COD_USUARIO_ASIG    INTEGER,
  USUARIO_ASIG        VARCHAR(50),
  FECHA_CREACION      TIMESTAMP,
  FECHA_ULTIMO_CAMBIO TIMESTAMP,
  AGENDA_FECHA        TIMESTAMP,
  AGENDA_COD_USUARIO  INTEGER,
  AGENDA_USUARIO      VARCHAR(50),
  ESTADO_PRESUPUESTO  VARCHAR(10)
)
AS
DECLARE VARIABLE V_FINALIZADO SMALLINT;
BEGIN
/*
  Nombre: PRV_LIST_TICKETS_BASE_AG
  Descripción: Cabecera de tickets con su estado actual (último movimiento), agenda más reciente y
               estado del presupuesto más reciente. Aplica todos los filtros salvo texto y paginación.
  Última modificación: 2026-10-17

  Precondiciones:
  - P_CREADO_DESDE <= P_CREADO_HASTA cuando ambos tienen valor (lo valida el público).
  - P_ESTADOS y P_PRIORIDADES son CSV sin espacios (los arma el MCP desde enums).

  Postcondiciones:
  - Una fila por ticket con al menos un movimiento. Sin filtro de visibilidad por usuario (igual que la v1).
  - Estado, resultado, asignado y FECHA_ULTIMO_CAMBIO salen del último movimiento de DET_RECLAMOS_CLIENTES
    (mayor FECHA_ORDEN, desempate por COD_MENSAJE_CLIENTE), igual que la v1.
  - Si P_ESTADOS tiene valor, se ignora P_SOLO_ABIERTOS. Abierto = ESTADOS_RECLAMOS.FINALIZADO = 0.
  - Nombres de persona = COALESCE(USUARIOS.NOMBRE, USUARIOS.ALIAS).
  - AGENDA_* = evento con FECHA_EVENTO más reciente (criterio de PROC_GET_TICKETS_ADMIN_PORTAL).
  - ESTADO_PRESUPUESTO = estado del presupuesto no anulado más reciente; NULL si no tiene.

  Rendimiento: el último movimiento se busca ticket por ticket con FIRST 1 sobre el índice de
  COD_RECLAMO (~1,6 s para recorrer los 35.000 tickets de testing). El NOT EXISTS de la v1 sobre
  todo DET_RECLAMOS_CLIENTES tardaba ~65 s para el mismo resultado.
*/
  FOR
    SELECT R.COD_RECLAMO,
           COALESCE(R.TITULO, 'Ticket ' || R.COD_RECLAMO),
           R.PEDIDO_NORMALIZADO, R.PRIORIDAD, R.TIPO_SISTEMA,
           R.COD_PROCESO_SISTEMA, PS.NOMBRE,
           R.COD_CLIENTE, CL.NOMBRE, R.CONTACTO, R.FECHA_HORA
    FROM RECLAMOS R
    LEFT JOIN PROCESOS_SISTEMAS PS ON PS.COD_PROCESO_SISTEMA = R.COD_PROCESO_SISTEMA
    LEFT JOIN CLIENTES CL ON CL.COD_CLIENTE = R.COD_CLIENTE
    WHERE (:P_COD_RECLAMO IS NULL OR R.COD_RECLAMO = :P_COD_RECLAMO)
      AND (:P_COD_CLIENTE IS NULL OR R.COD_CLIENTE = :P_COD_CLIENTE)
      AND (:P_PRIORIDADES IS NULL OR (',' || :P_PRIORIDADES || ',') CONTAINING (',' || R.PRIORIDAD || ','))
      AND (:P_SISTEMA IS NULL OR R.TIPO_SISTEMA = :P_SISTEMA)
      AND (:P_CREADO_DESDE IS NULL OR R.FECHA_HORA >= :P_CREADO_DESDE)
      AND (:P_CREADO_HASTA IS NULL OR R.FECHA_HORA < DATEADD(1 DAY TO :P_CREADO_HASTA))
      AND (:P_AGENDADO_A IS NULL OR EXISTS (
            SELECT 1
            FROM EVENTOS EA
            JOIN AGENDA_EVENTOS AEA ON AEA.COD_AGENDA_EVENTO = EA.COD_AGENDA
            WHERE EA.COD_RECLAMO = R.COD_RECLAMO
              AND AEA.COD_USUARIO = :P_AGENDADO_A))
    INTO :COD_RECLAMO, :TITULO, :PEDIDO_NORMALIZADO, :PRIORIDAD, :TIPO_SISTEMA,
         :COD_PROCESO_SISTEMA, :PROCESO_SISTEMA, :COD_CLIENTE, :CLIENTE, :CONTACTO, :FECHA_CREACION
  DO
  BEGIN
    /* Último movimiento. SELECT ... INTO sin filas no pisa las variables: se usa ROW_COUNT. */
    SELECT FIRST 1 ER.ESTADO, ER.FINALIZADO, RR.DESCRIPCION, D.COD_USUARIO_DESTINO,
           COALESCE(UD.NOMBRE, UD.ALIAS), D.FECHA_ORDEN
    FROM DET_RECLAMOS_CLIENTES D
    JOIN RESULTADOS_RECLAMOS RR ON RR.COD_RESULTADO_RECLAMO = D.COD_RESULTADO_RECLAMO
    JOIN ESTADOS_RECLAMOS ER ON ER.COD_ESTADO_RECLAMO = RR.COD_ESTADO_RECLAMO
    LEFT JOIN USUARIOS UD ON UD.COD_USUARIO = D.COD_USUARIO_DESTINO
    WHERE D.COD_RECLAMO = :COD_RECLAMO
    ORDER BY D.FECHA_ORDEN DESC, D.COD_MENSAJE_CLIENTE DESC
    INTO :ESTADO, :V_FINALIZADO, :RESULTADO, :COD_USUARIO_ASIG, :USUARIO_ASIG, :FECHA_ULTIMO_CAMBIO;
    IF (ROW_COUNT = 0) THEN CONTINUE;

    IF (:P_ESTADOS IS NOT NULL AND NOT ((',' || :P_ESTADOS || ',') CONTAINING (',' || ESTADO || ','))) THEN CONTINUE;
    IF (:P_ESTADOS IS NULL AND COALESCE(:P_SOLO_ABIERTOS, 1) = 1 AND V_FINALIZADO <> 0) THEN CONTINUE;
    IF (:P_COD_USUARIO_ASIG IS NOT NULL AND COALESCE(COD_USUARIO_ASIG, -1) <> :P_COD_USUARIO_ASIG) THEN CONTINUE;

    AGENDA_FECHA = NULL; AGENDA_COD_USUARIO = NULL; AGENDA_USUARIO = NULL;
    SELECT FIRST 1 E.FECHA_EVENTO, AE.COD_USUARIO, COALESCE(U.NOMBRE, U.ALIAS)
    FROM EVENTOS E
    JOIN AGENDA_EVENTOS AE ON AE.COD_AGENDA_EVENTO = E.COD_AGENDA
    LEFT JOIN USUARIOS U ON U.COD_USUARIO = AE.COD_USUARIO
    WHERE E.COD_RECLAMO = :COD_RECLAMO
    ORDER BY E.FECHA_EVENTO DESC, E.COD_EVENTO DESC
    INTO :AGENDA_FECHA, :AGENDA_COD_USUARIO, :AGENDA_USUARIO;

    ESTADO_PRESUPUESTO = NULL;
    SELECT FIRST 1 DECODE(RC.APROBADO, 1, 'APROBADO', 0, 'RECHAZADO', 'PENDIENTE')
    FROM RECLAMOS_COMPROBANTES RC
    JOIN COMPROBANTES C ON C.COD_TALONARIO = RC.COD_TALONARIO AND C.NRO_COMPROBANTE = RC.NRO_COMPROBANTE
    JOIN TIPOS_COMPROBANTES TC ON TC.COD_TIPO_COMPROBANTE = C.COD_TIPO_COMPROBANTE
    WHERE RC.COD_RECLAMO = :COD_RECLAMO
      AND TC.TIPO_COMPROBANTE = 'Presupuesto'
      AND COALESCE(C.ANULADO, 0) = 0
    ORDER BY C.FECHA DESC, RC.NRO_COMPROBANTE DESC
    INTO :ESTADO_PRESUPUESTO;

    SUSPEND;
  END
END^

SET TERM ; ^
