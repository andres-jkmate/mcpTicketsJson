CREATE OR ALTER PROCEDURE PROC_LIST_HIST_TICKET_AG (
  P_COD_RECLAMO          INTEGER,
  P_SOLO_VISIBLE_CLIENTE SMALLINT,
  P_LIMITE               INTEGER
)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255), TOTAL INTEGER,
  COD_MENSAJE_CLIENTE INTEGER, FECHA_HORA TIMESTAMP, TIPO_HITO VARCHAR(30), TEXTO_HITO BLOB SUB_TYPE 1,
  RESULTADO_RECLAMO VARCHAR(100), COD_USUARIO INTEGER, USUARIO VARCHAR(50),
  COD_USUARIO_DESTINO INTEGER, USUARIO_DESTINO VARCHAR(50), MENSAJE BLOB SUB_TYPE 1,
  ES_MENSAJE_CLIENTE SMALLINT, VISIBLE_CLIENTE SMALLINT, ADJUNTOS INTEGER, COD_MENSAJE_RESPUESTA INTEGER
)
AS
BEGIN
/*
  Nombre: PROC_LIST_HIST_TICKET_AG
  Descripción: Últimos P_LIMITE movimientos del ticket, devueltos en orden cronológico ascendente, con TOTAL.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_RECLAMO IS NULL OR :P_LIMITE IS NULL OR :P_LIMITE < 1 OR :P_LIMITE > 200) THEN
  BEGIN
    MENSAJE_ERROR = 'Ticket obligatorio y límite entre 1 y 200';
    SUSPEND; EXIT;
  END

  FOR
    SELECT X.TOTAL, X.COD_MENSAJE_CLIENTE, X.FECHA_HORA, X.TIPO_HITO, X.TEXTO_HITO, X.RESULTADO,
           X.COD_USUARIO, X.USUARIO, X.COD_USUARIO_DESTINO, X.USUARIO_DESTINO, X.MENSAJE,
           X.ES_MENSAJE_CLIENTE, X.VISIBLE_CLIENTE, X.ADJUNTOS, X.COD_MENSAJE_RESPUESTA
    FROM (
      SELECT H.*, COUNT(*) OVER () AS TOTAL, ROW_NUMBER() OVER (ORDER BY H.ORDEN DESC) AS RN
      FROM PRV_LIST_HIST_BASE_AG(:P_COD_RECLAMO) H
      WHERE COALESCE(:P_SOLO_VISIBLE_CLIENTE, 0) = 0 OR H.VISIBLE_CLIENTE = 1
    ) X
    WHERE X.RN <= :P_LIMITE
    ORDER BY X.ORDEN
    INTO :TOTAL, :COD_MENSAJE_CLIENTE, :FECHA_HORA, :TIPO_HITO, :TEXTO_HITO, :RESULTADO_RECLAMO,
         :COD_USUARIO, :USUARIO, :COD_USUARIO_DESTINO, :USUARIO_DESTINO, :MENSAJE,
         :ES_MENSAJE_CLIENTE, :VISIBLE_CLIENTE, :ADJUNTOS, :COD_MENSAJE_RESPUESTA
  DO
  BEGIN
    RESULTADO = 1; MENSAJE_ERROR = '';
    SUSPEND;
  END
END^

SET TERM ; ^
