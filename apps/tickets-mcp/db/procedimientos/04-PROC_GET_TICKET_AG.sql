CREATE OR ALTER PROCEDURE PROC_GET_TICKET_AG (
  P_COD_RECLAMO INTEGER
)
RETURNS (
  RESULTADO SMALLINT, MENSAJE_ERROR VARCHAR(255),
  COD_RECLAMO INTEGER, TITULO VARCHAR(200), ESTADO VARCHAR(50), RESULTADO_RECLAMO VARCHAR(100),
  PRIORIDAD VARCHAR(15), TIPO_SISTEMA VARCHAR(7), COD_PROCESO_SISTEMA INTEGER, PROCESO_SISTEMA VARCHAR(200),
  COD_CLIENTE INTEGER, CLIENTE VARCHAR(100), CONTACTO VARCHAR(100),
  COD_USUARIO_ASIG INTEGER, USUARIO_ASIG VARCHAR(50),
  FECHA_CREACION TIMESTAMP, FECHA_ULTIMO_CAMBIO TIMESTAMP, PEDIDO_NORMALIZADO BLOB SUB_TYPE 1
)
AS
BEGIN
/*
  Nombre: PROC_GET_TICKET_AG
  Descripción: Detalle de un ticket para agentes. 0 filas = el ticket no existe.
  Última modificación: 2026-10-16
*/
  RESULTADO = 0;
  IF (:P_COD_RECLAMO IS NULL) THEN
  BEGIN
    MENSAJE_ERROR = 'Falta el número de ticket';
    SUSPEND; EXIT;
  END

  FOR
    SELECT B.COD_RECLAMO, B.TITULO, B.ESTADO, B.RESULTADO, B.PRIORIDAD, B.TIPO_SISTEMA,
           B.COD_PROCESO_SISTEMA, B.PROCESO_SISTEMA, B.COD_CLIENTE, B.CLIENTE, B.CONTACTO,
           B.COD_USUARIO_ASIG, B.USUARIO_ASIG, B.FECHA_CREACION, B.FECHA_ULTIMO_CAMBIO, B.PEDIDO_NORMALIZADO
    FROM PRV_LIST_TICKETS_BASE_AG(:P_COD_RECLAMO, NULL, NULL, NULL, NULL, 0, NULL, NULL, NULL, NULL) B
    INTO :COD_RECLAMO, :TITULO, :ESTADO, :RESULTADO_RECLAMO, :PRIORIDAD, :TIPO_SISTEMA, :COD_PROCESO_SISTEMA,
         :PROCESO_SISTEMA, :COD_CLIENTE, :CLIENTE, :CONTACTO, :COD_USUARIO_ASIG, :USUARIO_ASIG,
         :FECHA_CREACION, :FECHA_ULTIMO_CAMBIO, :PEDIDO_NORMALIZADO
  DO
  BEGIN
    RESULTADO = 1; MENSAJE_ERROR = '';
    SUSPEND;
  END
END^

SET TERM ; ^
